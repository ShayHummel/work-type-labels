# Near-duplicates: nearest train neighbour (TF-IDF cosine), label agreement by similarity bucket.
vec = TfidfVectorizer(ngram_range=(1, 2), min_df=2, sublinear_tf=True)
Xtr = vec.fit_transform(train.text)
Xho = vec.transform(hold.text)
nn = NearestNeighbors(n_neighbors=2, metric="cosine").fit(Xtr)
dist_tr, idx_tr = nn.kneighbors(Xtr)
# first neighbour is the row itself (or an exact duplicate); take the first that is a different row
self_first = idx_tr[:, 0] == np.arange(len(train))
nb = np.where(self_first, idx_tr[:, 1], idx_tr[:, 0])
sim = 1 - np.where(self_first, dist_tr[:, 1], dist_tr[:, 0])
agree = train.label.values == train.label.values[nb]
buckets = pd.cut(sim, [0, .3, .5, .7, .8, .9, .95, 1.0001], right=False)
nn_tab = pd.DataFrame({"bucket": buckets, "agree": agree}).groupby("bucket", observed=True).agg(
    rows=("agree", "size"), label_agreement=("agree", "mean"))
md("Nearest-neighbour label agreement in train (TF-IDF 1–2-gram cosine):")
md()
table(nn_tab)
hi = sim >= 0.9
md(f"- Rows with a near-duplicate (cos ≥ 0.9): {hi.sum()} ({hi.mean():.1%}); of these, label disagrees "
   f"in {(~agree[hi]).mean():.1%}.")
md("- Label disagreement among near-duplicates is a lower bound on teacher inconsistency.")
md()
nd = pd.DataFrame({"a": train.label.values, "b": train.label.values[nb]})[hi & ~agree]
if len(nd):
    pairs = nd.apply(lambda r: " / ".join(sorted([r.a, r.b])), axis=1).value_counts().head(12)
    md("Most frequent conflicting label pairs among near-duplicates (cos ≥ 0.9):")
    md()
    table(pairs.rename("count").to_frame(), ".0f")
    md("Examples:")
    md()
    shown = 0
    for i in np.where(hi & ~agree)[0]:
        if i < nb[i]:
            a, b = train.iloc[i], train.iloc[nb[i]]
            md(f"- **{a.label}**: `{a.text[:160].replace(chr(10), ' ')}`  ")
            md(f"  **{b.label}**: `{b.text[:160].replace(chr(10), ' ')}`  (cos {sim[i]:.2f})")
            shown += 1
        if shown >= 8:
            break
    md()

d_ho, i_ho = nn.kneighbors(Xho, n_neighbors=1)
sim_ho = 1 - d_ho[:, 0]
