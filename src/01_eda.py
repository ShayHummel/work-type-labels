def norm(s: pd.Series) -> pd.Series:
    return s.str.lower().str.replace(r"\s+", " ", regex=True).str.strip()


train["norm"] = norm(train.text)
grp = train.groupby("norm").label.agg(["size", "nunique"])
dup_groups = grp[grp["size"] > 1]
md(f"- Normalized-text duplicate groups in train: {len(dup_groups)} "
   f"covering {dup_groups['size'].sum()} rows; groups with conflicting labels: "
   f"{(dup_groups['nunique'] > 1).sum()} ({(dup_groups['nunique'] > 1).mean():.1%} of groups)")
