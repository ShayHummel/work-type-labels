CODE_RE = re.compile(r"```|^\s{4,}\S|[{};]\s*$|\bdef \w+\(|\bfunction\b|\bimport \w|#include|=>|\bclass \w+",
                     re.M)
TRACE_RE = re.compile(r"Traceback \(most recent call last\)|\bat [\w.$]+\(.*:\d+\)|Error:|Exception|"
                      r"\berror\b.*line \d+|\bstack trace\b|npm ERR!|\bFAILED\b", re.I)
URL_RE = re.compile(r"https?://")


def featurize(df: pd.DataFrame) -> pd.DataFrame:
    t = df.text
    f = pd.DataFrame(index=df.index)
    f["chars"] = t.str.len()
    f["words"] = t.str.split().str.len()
    f["approx_tokens"] = (f.chars / 4).round()  # ~4 chars per subword token for English/code
    f["lines"] = t.str.count("\n") + 1
    f["has_code"] = t.str.contains(CODE_RE)
    f["has_trace"] = t.str.contains(TRACE_RE)
    f["has_url"] = t.str.contains(URL_RE)
    letters = t.str.count(r"[^\W\d_]")
    f["non_ascii_letter_frac"] = t.str.count(r"[^\x00-\x7F]") / letters.clip(lower=1)
    f["non_english"] = f.non_ascii_letter_frac > 0.3
    return f


