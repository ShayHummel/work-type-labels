# ---------------------------------------------------------------- 6. hard pairs: discriminative terms
md("## 6. Hard pairs — most discriminative words")
md()
md("Smoothed log-odds ratio (informative Dirichlet prior, Monroe et al. 2008) on unigrams+bigrams.")
md()
cv_vec = TfidfVectorizer(ngram_range=(1, 2), min_df=5, use_idf=False, norm=None, binary=True,
                         token_pattern=r"(?u)\b[a-zA-Z][a-zA-Z_]+\b")
B = cv_vec.fit_transform(train.text)
vocab = np.array(cv_vec.get_feature_names_out())
prior = np.asarray(B.sum(axis=0)).ravel() + 0.01
a0 = prior.sum()
for a, b in HARD_PAIRS:
    ya = np.asarray(B[(train.label == a).values].sum(axis=0)).ravel()
    yb = np.asarray(B[(train.label == b).values].sum(axis=0)).ravel()
    na, nb_ = ya.sum(), yb.sum()
    delta = (np.log((ya + prior) / (na + a0 - ya - prior)) - np.log((yb + prior) / (nb_ + a0 - yb - prior)))
    var = 1 / (ya + prior) + 1 / (yb + prior)
    z = delta / np.sqrt(var)
    top_a = vocab[np.argsort(-z)[:15]]
    top_b = vocab[np.argsort(z)[:15]]
    md(f"**{a}** vs **{b}**")
    md()
    md(f"- → {a}: {', '.join(top_a)}")
    md(f"- → {b}: {', '.join(top_b)}")
    for kw in {"Refactoring": ["refactor", "faster", "performance"], "Review": ["review", "explain"],
               "Architecting": ["design", "architecture"], "Setup": ["install", "error"]}.get(a, []):
        has = train.text.str.contains(rf"\b{kw}", case=False)
        md(f"  - rows containing `{kw}`: {a} {has[train.label == a].mean():.1%} vs "
           f"{b} {has[train.label == b].mean():.1%}; label mix of rows with it: "
           f"{train.label[has].value_counts(normalize=True).head(4).round(2).to_dict()}")
    md()

